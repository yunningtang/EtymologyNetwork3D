#!/usr/bin/env node
// Turns scripts/vocab/notes.tsv (word <TAB> 词源解释) into data/notes.js (window.WORD_NOTES).
// The notes are hand-written: each one walks from the parts' literal meanings to the word's
// real meaning, e.g. "in（进入）+ spect（看）：往里面仔细看，「检查」。"
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..');
const rows = fs.readFileSync(path.join(__dirname, 'notes.tsv'), 'utf8').split('\n').map(l => l.split('\t')).filter(r => r[0] && r[1]);
const notes = {};
for (const [w, note] of rows) { if (notes[w]) console.warn('duplicate: ' + w); notes[w.trim().toLowerCase()] = note.trim(); }
fs.writeFileSync(path.join(ROOT, 'data', 'notes.js'),
  '// Generated by scripts/vocab/build-notes.js from scripts/vocab/notes.tsv — edit the TSV, not this file.\n' +
  '// word → 词源解释（从字面义到实际义）\n' +
  'window.WORD_NOTES = ' + JSON.stringify(notes, null, 0).replace(/","/g, '",\n"') + ';\n');
console.log(Object.keys(notes).length + ' notes → data/notes.js');
